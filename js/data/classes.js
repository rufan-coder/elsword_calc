const pct = x => x / 100;

function toClass([name, type, tier, crit, critDmg, maxi, boss, hp]) {
  const skill = SKILL_DAMAGE_PASSIVE[name] || { gang: 0, cho: 0 };
  return {
    name, type, tier,
    crit_s: pct(crit[0]), crit_m: pct(crit[1]), crit_a: pct(crit[2]),
    cd_s: pct(critDmg[0]), cd_final: pct(critDmg[1]), cd_base: pct(critDmg[2]),
    maxi_s: pct(maxi[0]), maxi_m: pct(maxi[1]), maxi_a: pct(maxi[2]),
    boss: pct(boss),
    hp_over: hp[0] - 1, hp_under: hp[1] - 1,
    gang: pct(skill.gang), cho: pct(skill.cho),
  };
}

/** 전직 이름 -> 패시브 정보. 수치는 모두 비율(0.15 = 15%)로 바꿔 둔다. */
export const CLASS = Object.fromEntries(TABLE.map(row => [row[0], toClass(row)]));

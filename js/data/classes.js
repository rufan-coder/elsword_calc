const pct = x => x / 100;

function toClass([name, type, tier, crit, critDmg, maxi, boss, hp]) {
  const skill = SKILL_DAMAGE_PASSIVE[name] || { gang: 0, cho: 0 };
  const extra = CLASS_EXTRA[name] || {};
  return {
    name, type, tier,
    crit_s: pct(crit[0]), crit_m: pct(crit[1]), crit_a: pct(crit[2]),
    cd_s: pct(critDmg[0]), cd_final: pct(critDmg[1]), cd_base: pct(critDmg[2]),
    maxi_s: pct(maxi[0]), maxi_m: pct(maxi[1]), maxi_a: pct(maxi[2]),
    boss: pct(boss),
    hp_over: hp[0] - 1, hp_under: hp[1] - 1,
    gang: pct(skill.gang), cho: pct(skill.cho),
    atk_s: pct(extra.atk_s || 0),
    hp_crit_over: pct(extra.hp_crit ? extra.hp_crit[0] : 0), hp_crit_under: pct(extra.hp_crit ? extra.hp_crit[1] : 0),
    cdr_cap: extra.cdr_cap == null ? null : pct(extra.cdr_cap),
  };
}

/** 전직 이름 -> 패시브 정보. 수치는 모두 비율(0.15 = 15%)로 바꿔 둔다. */
export const CLASS = Object.fromEntries(TABLE.map(row => [row[0], toClass(row)]));

/** 선택 스킬을 고른 전직 패시브. 고를 스킬이 없거나 모르는 선택지면 기본값(체인지)을 쓴다 */
export function withClassSkill(name, choice) {
  const job = CLASS[name], info = CLASS_SKILLS[name];
  if (!job || !info) return job;
  const o = info.options[choice] || info.options[info.default];
  return Object.assign({}, job, {
    skillChoice: info.options[choice] ? choice : info.default,
    crit_s: job.crit_s + pct(o.crit_s || 0),
    crit_m: job.crit_m + pct(o.crit_m || 0),
    cd_base: (1 + job.cd_base) * (1 + pct(o.cd_base || 0)) - 1,
  });
}
